(() => {
  const scroller = document.querySelector('.timeline-scroll');
  const wrap = document.querySelector('.timeline-scroll-wrap');

  if (!scroller || !wrap) return;

  const updateTimelineEdge = () => {
    const max = Math.max(0, scroller.scrollWidth - scroller.clientWidth);
    wrap.classList.toggle('is-end', max === 0 || scroller.scrollLeft >= max - 8);
  };

  let dragging = false;
  let pointerId = null;
  let startX = 0;
  let startScrollLeft = 0;

  const stopDrag = () => {
    if (!dragging) return;

    dragging = false;
    scroller.classList.remove('is-dragging');

    if (pointerId !== null && scroller.hasPointerCapture?.(pointerId)) {
      scroller.releasePointerCapture(pointerId);
    }

    pointerId = null;
  };

  scroller.addEventListener('pointerdown', (event) => {
    // Touch keeps browser-native inertial scrolling.
    if (event.pointerType === 'touch' || event.button !== 0) return;

    const rect = scroller.getBoundingClientRect();

    // Do not intercept the native horizontal scrollbar.
    // clientHeight excludes the scrollbar while getBoundingClientRect() includes it.
    const scrollbarTop = rect.top + scroller.clientHeight;
    if (event.clientY >= scrollbarTop) return;

    dragging = true;
    pointerId = event.pointerId;
    startX = event.clientX;
    startScrollLeft = scroller.scrollLeft;

    scroller.classList.add('is-dragging');
    scroller.setPointerCapture?.(event.pointerId);
  });

  scroller.addEventListener('pointermove', (event) => {
    if (!dragging || event.pointerId !== pointerId) return;

    // 1:1 mapping: no smoothing, easing, inertia or competing animation frames.
    scroller.scrollLeft = startScrollLeft - (event.clientX - startX);
    updateTimelineEdge();
    event.preventDefault();
  });

  scroller.addEventListener('pointerup', stopDrag);
  scroller.addEventListener('pointercancel', stopDrag);
  scroller.addEventListener('lostpointercapture', stopDrag);
  scroller.addEventListener('dragstart', (event) => event.preventDefault());

  scroller.addEventListener('scroll', updateTimelineEdge, { passive: true });
  window.addEventListener('resize', updateTimelineEdge);

  updateTimelineEdge();
})();

